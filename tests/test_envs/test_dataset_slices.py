'''Every collector's output must reproduce bit-exactly.

Five collectors produce the repo's dataset families, and they are about to be
unified into one. That refactor is unverifiable without oracles: dataset
semantics can shift with every suite green, and the shift surfaces weeks later
as bad model behaviour rather than a red test.

Each fixture records what a collector actually wrote -- starts, labels, terminal
states -- plus the exact argv that produced it. Re-running that command must
reproduce all three at atol=1e-12.

Parameterised over whichever fixtures exist, so this file is committed before
any of them and strengthens as each lands. Fixtures are generated by
tests/fixtures/capture_dataset_slice.py.

Deliberately NOT asserted: anything derived from compute_invariant_sets.py.
quad2d's ellipsoid does not reproduce (a ReLU crease inside fd_linearize's
stencil, see .claude/docs/datasets.md), so these pin collector output only.
'''
import glob
import json
import os
import subprocess
import sys

import numpy as np
import pytest

FIX = os.path.join(os.path.dirname(__file__), 'fixtures')
REPO = os.path.join(os.path.dirname(__file__), '..', '..')

# The pendulum's two slices predate this file and have their own test.
LEGACY = {'dataset_slice_lqr.json', 'dataset_slice_v3_strong.json'}


def _fixtures():
    found = sorted(glob.glob(os.path.join(FIX, 'dataset_slice_*.json')))
    return [f for f in found if os.path.basename(f) not in LEGACY]


def _read_labels(root):
    '''Parse roa_labels.txt: one line per rollout, `state..., label`.'''
    starts, labels = [], []
    with open(os.path.join(root, 'roa_labels.txt')) as handle:
        for line in handle:
            parts = [float(p) for p in line.strip().split(',') if p]
            if not parts:
                continue
            starts.append(parts[:-1])
            labels.append(int(parts[-1]))
    return starts, labels


def _read_terminals(root, count):
    '''Last state of each trajectories/sequence_<i>.txt.'''
    terminals = []
    for i in range(count):
        path = os.path.join(root, 'trajectories', f'sequence_{i}.txt')
        rows = np.loadtxt(path, delimiter=',', ndmin=2)
        terminals.append(rows[-1].tolist())
    return terminals


@pytest.mark.parametrize('fixture', _fixtures(),
                         ids=lambda f: os.path.basename(f)[len('dataset_slice_'):-len('.json')])
def test_slice_reproduces(fixture, tmp_path):
    golden = json.loads(open(fixture).read())

    out = tmp_path / 'out'
    command = [sys.executable] + golden['command'] + ['--output_dir', str(out)]
    result = subprocess.run(command, cwd=REPO, capture_output=True, text=True)
    assert result.returncode == 0, result.stderr[-3000:]

    starts, labels = _read_labels(str(out))
    assert len(starts) == golden['n'], \
        f'rollout count changed: {len(starts)} vs {golden["n"]}'
    assert labels == golden['labels'], 'success labels changed'
    np.testing.assert_allclose(starts, golden['starts'], atol=1e-12)

    terminals = _read_terminals(str(out), golden['n'])
    np.testing.assert_allclose(terminals, golden['terminal_states'], atol=1e-12)


@pytest.mark.parametrize('fixture', _fixtures(),
                         ids=lambda f: os.path.basename(f)[len('dataset_slice_'):-len('.json')])
def test_slice_exercises_both_labels(fixture):
    '''A fixture where every rollout has the same label pins almost nothing.

    A regression that inverted or broke the success rule would still reproduce
    a uniformly-labelled slice, so the oracle has to see both outcomes to be
    worth running.
    '''
    golden = json.loads(open(fixture).read())
    distinct = set(golden['labels'])
    assert distinct == {0, 1}, \
        f'fixture has labels {distinct}; it must contain both successes and failures'
